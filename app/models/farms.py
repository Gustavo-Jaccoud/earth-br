from typing import Literal

from pydantic import BaseModel


class GeoJSONPolygon(BaseModel):
    type: Literal["Polygon"]
    coordinates: list[list[tuple[float, float]]]  # [anel][ponto] = (lon, lat)


class FarmCreate(BaseModel):
    name: str
    municipality: str
    state: str
    ibge_code: str | None = None
    owner: str | None = None


class Farm(FarmCreate):
    id: int


class PlotCreate(BaseModel):
    name: str
    current_crop: str | None = None
    # Real boundary of the field (any valid polygon, e.g. drawn by the user on the map).
    geometry: GeoJSONPolygon


class Plot(PlotCreate):
    id: int
    farm_id: int
    # Square with the same area as the boundary, centred on it. It is the spatial reference for
    # NASA POWER queries; `geometry` (the real boundary) is what maps show and what satellite
    # rasters are clipped by. Generated by the server.
    query_geometry: GeoJSONPolygon
    centroid: tuple[float, float]  # (lon, lat): centre of query_geometry, the NASA POWER point
    area_ha: float  # area of the real boundary
    in_demo_region: bool
